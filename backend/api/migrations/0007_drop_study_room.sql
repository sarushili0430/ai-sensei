--
-- 0006 のファイルは消さない。マイグレーションは**追記だけ**にする:
-- 既に適用済みの本番DBでは、ファイルを消しても `study_room_daily` は残り続ける
-- (wrangler は未適用のものしか流さない)。リポジトリの履歴からだけ消えると、
-- 誰も掃除できない表がDBに居座ることになる。
--
-- ここで消えるのは滞在秒数とローカル日付だけで、学習内容(板書・単元・発話)は
-- もともとこの表に入っていない。授業・カルテ・穴・計画のデータには触れない。
--
-- デプロイはマイグレーションがWorkerより先に走る。POST /v1/me/study-room は
-- Worker側でも同時に消えるが、順序上「表が無いのに旧Workerが書きに来る」瞬間が
-- ありうる。そのときは INSERT が失敗して 500 を返すだけで、アプリ側は
-- この応答を表示せず捨てる実装だったため、生徒の画面には何も起きない。
DROP TABLE IF EXISTS study_room_daily;
